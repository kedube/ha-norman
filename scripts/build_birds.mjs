// Build the birds that cross the sidebar page's view.
//
//     node scripts/build_birds.mjs <ha-light-control>/src/house/birds.ts
//
// The birds are the models from the Light Control card (github.com/kedube/ha-light-control, by
// the same author): each kind's shape, colours, wingbeat and lighting. That card is written in
// TypeScript and built; this integration ships plain modules with no build step. So this takes
// the card's birds.ts, removes its types and nothing else, and writes
// custom_components/norman/www/norman-birds.js. Change the birds there, in the card, and run
// this again; a change made to the copy is lost the next time.
//
// Needs Node 22.13 or later, for module.stripTypeScriptTypes.

import { readFile, writeFile } from "node:fs/promises";
import { stripTypeScriptTypes } from "node:module";
import { fileURLToPath } from "node:url";

const [source] = process.argv.slice(2);
if (!source) {
  console.error("usage: node scripts/build_birds.mjs <path to birds.ts>");
  process.exit(1);
}
const OUT = fileURLToPath(new URL("../custom_components/norman/www/norman-birds.js", import.meta.url));

const original = (await readFile(source, "utf8")).split("\n");
// Stripping replaces every type with spaces, so the two files line up line for line.
const stripped = stripTypeScriptTypes(original.join("\n"), { mode: "strip" }).split("\n");

const blank = (line) => line.trim() === "";
// A line that held only types: an interface, a type alias, a type-only import.
const erased = stripped.map((line, index) => blank(line) && !blank(original[index]));
const comment = (line) => /^\s*(\/\/|\/\*|\*)/.test(line);

const kept = [];
for (let index = 0; index < stripped.length; index += 1) {
  if (erased[index]) {
    // The comment above a type that is gone describes nothing now.
    while (kept.length && comment(kept[kept.length - 1])) kept.pop();
    continue;
  }
  let line = stripped[index];
  if (line !== original[index]) {
    // Close the gaps the types left inside a line: `(v        , lo        )` is `(v, lo)`.
    const indent = /^\s*/.exec(line)[0];
    line = indent + line.slice(indent.length).replace(/ {2,}/g, " ").replace(/ ([,;)])/g, "$1").trimEnd();
  }
  kept.push(line);
}
// One blank line where several are left.
const body = kept.filter((line, index) => !(blank(line) && blank(kept[index - 1] ?? ""))).join("\n").trim();

const header = `/**
 * Birds for the Norman Shades view (norman-view.js): small 3D models of seven kinds, each with
 * its own shape, colours and way of flying.
 *
 * GENERATED by scripts/build_birds.mjs from the Light Control card's src/house/birds.ts
 * (github.com/kedube/ha-light-control, by the same author), with its types removed and nothing
 * else changed. Change the birds in that card and build this again; do not edit it here.
 *
 * Loaded by the view only when a photograph has birds in its sky, at the view's own ?v= stamp.
 */

`;
await writeFile(OUT, `${header}${body}\n`);
console.log(`norman-birds.js: ${header.length + body.length + 1} bytes`);
